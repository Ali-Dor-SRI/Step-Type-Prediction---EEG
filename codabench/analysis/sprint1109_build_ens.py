def main():
    src = X4F.read_text(encoding="utf8")
    assert src.count("\nclass Solver(CompetSolver):") == 1
    src = src.replace("\nclass Solver(CompetSolver):", "\nclass _X4fSolver(CompetSolver):")
    net = NET.read_text(encoding="utf8")
    net = net[net.index("class _CombinedConv"):]      # drop docstring + imports (already imported)
    OUT.write_text(HEADER + "\n# ===== X4f solver (riemann_sealed_proteus_x4f.py, verbatim) =====\n"
                   + src + "\n\n# ===== ShallowNetT (analysis/shallownet_t.py, verbatim) =====\n"
                   + net + TAIL, encoding="utf8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
