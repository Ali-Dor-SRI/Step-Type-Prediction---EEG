#!/usr/bin/env python
"""Compact EDA of the PROTEUS window cache (sprint 2026-10-16; RELEASE_DAY § 5 step 3).

Aimed at what the candidate model (F64: per-stream covariance + feature
re-centring) relies on. From the cache only (windows = cue + 1 s .. + 5 s; no
pre-cue baseline, so no ERD relative to rest):
  1. session shift: Riemannian distance between each session's mean covariance and
     the pooled mean of everyone else (unseen-person shift), and between P04/P10's
     own sessions (later-session shift);
  2. how fast a stream's running reference settles: distance of the running mean
     after n windows to the session's full mean, n = 8, 16, 32, 64, 128 (median over
     the 14 sessions), in stream order;
  3. where the class signal is: per person, the Fisher ratio (between-class over
     within-class variance) of log band power, averaged over channels of each
     region, per band; and the run-type split (calibration vs online) of that ratio.
Writes reports/proteus_eda/EDA.md.

    python ~/codabench/analysis/proteus_eda.py
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.signal import welch

sys.path.insert(0, str(Path.home() / "codabench/analysis"))
import proteus_cache as PC  # noqa: E402
import proteus_splits as PS  # noqa: E402

OUT = Path.home() / "codabench/reports/proteus_eda"
BANDS = {"theta 4-8": (4, 8), "alpha 8-13": (8, 13), "beta 13-30": (13, 30)}


def covs(X):
    Xc = X - X.mean(-1, keepdims=True)
    C = np.einsum("nct,ndt->ncd", Xc, Xc) / X.shape[-1]
    tr = np.trace(C, axis1=1, axis2=2)[:, None, None] / X.shape[1]
    return C + 1e-3 * tr * np.eye(X.shape[1])[None]


def logm(C):
    w, V = np.linalg.eigh(C)
    return (V * np.log(np.maximum(w, 1e-12))) @ V.T


def le_mean(Cs):
    L = np.mean([logm(c) for c in Cs], 0)
    w, V = np.linalg.eigh(L)
    return (V * np.exp(w)) @ V.T


def dist(A, B):
    """Affine-invariant Riemannian distance."""
    w, V = np.linalg.eigh(A)
    Ai = (V / np.sqrt(w)) @ V.T
    m = np.linalg.eigvalsh(Ai @ B @ Ai)
    return float(np.sqrt(np.sum(np.log(np.maximum(m, 1e-12)) ** 2)))


def region(name):
    n = name.upper()
    if n.startswith(("FP", "AF", "F")) and not n.startswith("FC"):
        return "frontal"
    if n.startswith(("FC", "C")) and not n.startswith("CP"):
        return "central"
    if n.startswith(("CP", "P")) and not n.startswith("PO"):
        return "parietal"
    if n.startswith(("PO", "O")):
        return "occipital"
    if n.startswith(("T", "FT", "TP")):
        return "temporal"
    return "other"


def main():
    c = PC.load()
    rows, X, y = c.rows, c.X, c.y
    ch = list(c.meta["ch_names"])
    sf = float(c.meta["sfreq"])
    keys = list(rows.groupby(["person", "session"]).groups)
    lines = ["# PROTEUS EDA (window cache; sprint 2026-10-16)", "",
             f"Data: {len(rows)} windows, {X.shape[1]} channels, {X.shape[2]} samples at {sf:g} Hz, "
             f"{len(keys)} sessions of {rows.person.nunique()} people. Windows start 1 s after the cue "
             "(feedback onset at +3 s, i.e. 2 s into the window). Generated by "
             "`analysis/proteus_eda.py`.", ""]

    # 1. session shift ------------------------------------------------------------------
    sess_mean, sess_cov = {}, {}
    for k in keys:
        idx = PS.stream_order(rows, np.where((rows.person == k[0]) & (rows.session == k[1]))[0])
        C = covs(np.asarray(X[idx], dtype=np.float64))
        sess_cov[k] = (idx, C)
        sess_mean[k] = le_mean(C)
    lines += ["## 1. How far apart sessions are (Riemannian distance of mean covariances)", "",
              "| session | to the pooled mean of the other people | to its own person's other sessions |",
              "|---|---|---|"]
    for k in keys:
        others = [sess_mean[j] for j in keys if j[0] != k[0]]
        own = [dist(sess_mean[k], sess_mean[j]) for j in keys if j[0] == k[0] and j != k]
        lines.append(f"| {k[0]} s{k[1]} | {dist(sess_mean[k], le_mean(others)):.2f} | "
                     + (f"{np.mean(own):.2f}" if own else "—") + " |")
    between = [dist(sess_mean[a], sess_mean[b]) for i, a in enumerate(keys) for b in keys[i + 1:]
               if a[0] != b[0]]
    within = [dist(sess_mean[a], sess_mean[b]) for i, a in enumerate(keys) for b in keys[i + 1:]
              if a[0] == b[0]]
    lines += ["", f"Pairs of sessions: different people median {np.median(between):.2f} "
              f"(range {min(between):.2f}–{max(between):.2f}); same person (P04, P10) median "
              f"{np.median(within):.2f} (range {min(within):.2f}–{max(within):.2f}). A session sits "
              "far from everyone else's mean: this is the shift the per-stream re-centring removes.", ""]

    # 2. running reference settling -----------------------------------------------------
    ns = (8, 16, 32, 64, 128)
    rel = {n: [] for n in ns}
    for k in keys:
        idx, C = sess_cov[k]
        full = sess_mean[k]
        base = dist(le_mean([sess_mean[j] for j in keys if j[0] != k[0]]), full)
        for n in ns:
            if n <= len(C):
                rel[n].append(dist(le_mean(C[:n]), full) / base)
    lines += ["## 2. How fast a session's running reference settles", "",
              "Distance from the running mean of the first n windows (stream order) to the session's "
              "full mean, relative to the distance of the other people's pooled mean (= the reference "
              "a model without re-centring uses). Median over the 14 sessions.", "",
              "| n windows | " + " | ".join(str(n) for n in ns) + " |",
              "|---|" + "---|" * len(ns),
              "| relative distance | " + " | ".join(f"{np.median(rel[n]):.2f}" for n in ns) + " |", "",
              "Below 1 = already closer to the session's own centre than the training mean is. "
              "Runs inside a session change paradigm (calibration runs 1–2, online runs 3–6) and "
              "interface, so a short buffer also follows within-session drift.", ""]

    # 3. class signal ------------------------------------------------------------------
    f, P = welch(np.asarray(X, dtype=np.float64), fs=sf, nperseg=int(sf), axis=-1)
    reg = np.array([region(n) for n in ch])
    lines += ["## 3. Where the class signal is (Fisher ratio of log band power)", "",
              "Per person, per channel: between-class variance of log band power over the "
              "within-class variance (3 classes; 0 = no separation). Mean over the channels of a "
              "region, then median over the 10 people.", "",
              "| band | " + " | ".join(r for r in ("frontal", "central", "parietal", "occipital",
                                                   "temporal")) + " | best single channel (median over people) |",
              "|---|---|---|---|---|---|---|"]
    fish_rt = {"calib": [], "online": []}
    for bname, (lo, hi) in BANDS.items():
        bp = np.log(P[:, :, (f >= lo) & (f < hi)].mean(-1))           # (n, C)
        per_person = []
        for p in sorted(rows.person.unique()):
            m = (rows.person == p).to_numpy()
            b, yy = bp[m], y[m]
            mu = b.mean(0)
            between = sum(((b[yy == k].mean(0) - mu) ** 2) * (yy == k).mean() for k in range(3))
            within = sum(b[yy == k].var(0) * (yy == k).mean() for k in range(3))
            per_person.append(between / within)
            if bname == "alpha 8-13":
                for rt, sel in (("calib", rows.task.str.startswith("Acquisition")),
                                ("online", ~rows.task.str.startswith("Acquisition"))):
                    mm = m & sel.to_numpy()
                    b2, y2 = bp[mm], y[mm]
                    mu2 = b2.mean(0)
                    bt = sum(((b2[y2 == k].mean(0) - mu2) ** 2) * (y2 == k).mean() for k in range(3))
                    wt = sum(b2[y2 == k].var(0) * (y2 == k).mean() for k in range(3))
                    fish_rt[rt].append(float(np.mean(bt / wt)))
        fr = np.median(np.stack(per_person), 0)                      # (C,)
        cells = [f"{fr[reg == r].mean():.3f}" if np.any(reg == r) else "—"
                 for r in ("frontal", "central", "parietal", "occipital", "temporal")]
        best = int(np.argmax(fr))
        lines.append(f"| {bname} | " + " | ".join(cells) + f" | {ch[best]} {fr[best]:.3f} |")
    lines += ["", f"Alpha band, channel-mean Fisher ratio by run type (median over people): calibration "
              f"{np.median(fish_rt['calib']):.3f}, online {np.median(fish_rt['online']):.3f}.", ""]

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "EDA.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
